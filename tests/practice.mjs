// Run with PLAYWRIGHT_PATH pointing to an existing Playwright installation.
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright')
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const click = (name) => page.getByRole('button', { name, exact: true }).click()
async function start(lesson, mode = 'guided') {
  await page.goto('http://127.0.0.1:5173')
  await page.evaluate(({ lesson, mode }) => {
    localStorage.clear()
    Object.entries({ view: 'lab', 'active-lesson': lesson, 'practice-mode': mode }).forEach(([k,v]) => localStorage.setItem(`digital-ustaad:${k}`, JSON.stringify(v)))
  }, { lesson, mode })
  await page.reload()
  await page.getByRole('button', { name: 'Android home', exact: true }).waitFor()
}
async function result() {
  await page.getByRole('button', { name: 'See my progress', exact: false }).waitFor()
  return page.evaluate(() => JSON.parse(localStorage.getItem('digital-ustaad:progress')).latestResult)
}
async function photo({ backtrack = false } = {}) {
  await click('Open Gallery practice app')
  await page.getByRole('button', { name: /^Open photo:/ }).first().click()
  if (backtrack) {
    await click('Android back')
    await page.getByRole('button', { name: /^Open photo:/ }).nth(1).click()
  }
  await click('Share this practice photo')
  await page.getByRole('option', { name: 'Ammi', exact: false }).click()
  await page.getByRole('option', { name: 'Abu', exact: false }).click()
  if (backtrack) {
    await click('Close share sheet')
    await click('Share this practice photo')
    await page.getByRole('option', { name: 'Ammi', exact: false }).click()
  }
  await click('Confirm share in practice mode')
  assert.equal((await result()).completed, true)
}
async function chat() {
  await click('Open WhatsApp practice app')
  await page.getByRole('button', { name: /Ammi/ }).click()
}
